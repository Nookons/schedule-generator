import type {
  DayMarkKind,
  ShiftPreference,
  ShiftType,
  SubjectKey,
} from "@/lib/api/types"

/**
 * Работник в том виде, в каком его понимает генератор смен.
 *
 * `subject` — ссылка вида `e61` (работник) или `w3` (человек без регистрации).
 * Именно ею сервер адресует смены, отметки и место в составе, поэтому она же
 * служит ключом во всех внутренних картах.
 *
 * Тип намеренно уже, чем раньше: поля `position`, `contractType` и `daysOff`
 * убраны — в базе их нет, интерфейс не показывал, а генератор не использовал.
 * Пустые поля создавали впечатление, что они на что-то влияют.
 *
 * Цвета работника здесь нет намеренно. Свой цвет был у каждой строки, но
 * смысла не нёс: поверх него лежали цвета смен, и в таблице на десять человек
 * получалась радуга, в которой не разобрать, где день, а где ночь. Цвет
 * остался за состоянием дня (`lib/dayVisual.ts`), а строку менеджер находит по
 * имени.
 */
export interface IUser {
  /** Ссылка `e61` / `w3` — ключ, по которому смена уходит на сервер. */
  subject: SubjectKey

  /** Зарегистрирован в tk-assist или заведён одним именем. */
  kind: "employee" | "worker"

  /** `employees.id` или `schedule_unregistered_workers.id`. */
  id: number

  fullName: string
  warehouse: string | null
  priority: number
  shiftPreference: ShiftPreference

  /** Числа месяца, когда работник не может выходить (постоянная настройка). */
  daysOffUsers: number[]

  /**
   * Отметки дня на выбранный месяц: выходной, отпуск, больничный.
   * Действуют на всех складах, поэтому генератор обязан их учитывать.
   */
  marks: Record<number, DayMarkKind>

  /**
   * Смены этого человека на ДРУГИХ складах в том же месяце.
   * База не даст поставить его дважды в один день, но узнать об этом отказом
   * при сохранении поздно — планировщик должен знать заранее.
   */
  externalShifts: Record<number, { shiftType: ShiftType; warehouse: string }>

  /**
   * Смены в конце ПРЕДЫДУЩЕГО месяца, по всем складам.
   *
   * День — смещение назад от первого числа планируемого месяца: `0` — последний
   * день предыдущего, `-1` — предпоследний. Они не показываются в таблице и не
   * попадают в график: нужны только правилам, чтобы ночь 31-го не превратилась
   * в день 1-го. Правило отдыха вычитает из числа дня и попадает ровно в эти
   * значения, поэтому отрицательные дни продолжает та же нумерация.
   */
  previousShifts: { day: number; shiftType: ShiftType; warehouse: string }[]
  dayShifts: number[]
  nightShifts: number[]

  /**
   * Дни, закреплённые менеджером: он поставил туда смену кликом по клетке.
   *
   * Признак живёт в базе (`schedule_shifts.pinned`), потому что переживает
   * генерацию: «Построить график» пересобирает месяц, но закреплённые дни
   * остаются на месте. Закрепление ставится само при ручной правке дня и
   * снимается через меню дня или очисткой дня.
   */
  pinnedDays: number[]

  minShiftsPerMonth: number
  maxShiftsPerMonth: number

  isActive: boolean

  /** Есть ли на выбранный месяц переопределение предпочтений. */
  hasMonthOverride: boolean

  note: string | null
}
