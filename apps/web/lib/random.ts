/**
 * Воспроизводимый источник случайности.
 *
 * Алгоритм построения графика разрывает ничьи случайным шумом: без него
 * одинаковые кандидаты всегда решались бы в пользу первого в списке, и одни и
 * те же люди получали бы первый выбор каждый раз.
 *
 * Но случайность обязана быть воспроизводимой. Кнопка «Построить график» при
 * одних и тех же данных должна давать один и тот же месяц: если смены при
 * каждом нажатии прыгают, менеджер не может ни согласовать график, ни понять,
 * что изменилось от его правки. Поэтому зерно выводится из самих данных
 * (`hashString` в генераторе), а `Math.random()` в боевом пути не участвует.
 *
 * Тесты и разбор инцидентов подставляют зерно явно — тогда прогон повторяем
 * до последней смены.
 */

/** Источник случайности: возвращает число из [0, 1). */
export type RandomSource = () => number

/**
 * Детерминированный генератор случайных чисел (mulberry32).
 *
 * Выбран за то, что он короткий, без зависимостей и одинаково работает везде:
 * для разрыва ничьих важна не криптография, а повторяемость. Одно и то же
 * зерно всегда даёт одну и ту же последовательность, поэтому прогон можно
 * воспроизвести и починить.
 */
export function seededRandom(seed: number): RandomSource {
  let state = seed >>> 0

  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/**
 * Хеш строки в 32-битное число (FNV-1a) — из него получается зерно.
 *
 * Криптостойкость здесь не нужна и вредна: от хеша требуется только
 * устойчивость — одинаковая строка всегда даёт одно число. Совпадение хешей у
 * разных входов не портит график: зерно влияет лишь на разрыв ничьих, а сама
 * раскладка целиком определяется данными. Худшее, что может случиться, — два
 * разных состава получат одинаковую последовательность случайных чисел.
 *
 * `Math.imul` вместо умножения с плавающей точкой: произведение 32-битных чисел
 * выходит за пределы точности `double`, и обычное `*` теряло бы младшие биты —
 * хеш вырождался бы и перестал различать похожие строки.
 */
export function hashString(value: string): number {
  let hash = 2166136261

  for (let i = 0; i < value.length; i++) {
    hash ^= value.charCodeAt(i)
    hash = Math.imul(hash, 16777619)
  }

  return hash >>> 0
}
