import dayjs, { type Dayjs } from "dayjs"

/**
 * Докуда алгоритм не имеет права трогать месяц.
 *
 * Прошедшие дни — это история: человек уже отработал, и переставлять ему смены
 * задним числом нельзя. Поэтому в текущем месяце построение графика начинается
 * с завтрашнего дня, а сегодняшний остаётся таким, какой есть.
 *
 * Прошлые месяцы сюда намеренно не попадают: речь была про текущий, а
 * планировщик умеет строить месяц с нуля — например, когда график на прошлый
 * месяц не составляли и его нужно заполнить задним числом.
 *
 * Возвращается число дня включительно. `0` — месяц не ограничен.
 *
 * Граница считается по местному времени браузера: «сегодня» для менеджера —
 * это его сегодня, а не UTC. Часового пояса склада в системе нет, и заводить
 * его здесь значило бы придумать правило, которого больше нигде не существует.
 */
export function frozenThroughDay(month: string, today: Dayjs = dayjs()): number {
  if (month !== today.format("YYYY-MM")) return 0
  return today.date()
}
