import dayjs from "dayjs"
import "dayjs/locale/ru"

/**
 * Единственный dayjs приложения — с русской локалью.
 *
 * Интерфейс планировщика русский, а dayjs по умолчанию печатает месяцы
 * по-английски. Локаль задаётся здесь один раз, поэтому месяц в шапке экрана,
 * в диалоге состава и в имени листа Excel выглядит одинаково: иначе на одном
 * экране соседствовали бы «сентябрь 2026» и «September 2026».
 *
 * Импортировать день работы с датами нужно отсюда, а не из `dayjs`: тогда
 * регистрация локали гарантированно выполнится до первого форматирования и не
 * будет зависеть от порядка импортов.
 *
 * На вычисления это не влияет: `daysInMonth()`, `date()` и `day()` от локали не
 * зависят — она меняет только названия месяцев и дней недели.
 */
dayjs.locale("ru")

export default dayjs
