import { describe, expect, it } from "vitest"

import dayjs from "@/lib/dayjs"

/**
 * Тесты единственного dayjs приложения.
 *
 * Проверяются две вещи: что локаль действительно русская (иначе месяц в шапке и
 * в диалоге состава снова разойдётся) и что она не влияет на вычисления —
 * дни месяца, числа и день недели от названий месяцев зависеть не должны.
 */

describe("локаль планировщика", () => {
  it("печатает месяц по-русски", () => {
    expect(dayjs("2026-09-01").format("MMMM YYYY")).toBe("сентябрь 2026")
  })

  it("не сдвигает календарные вычисления", () => {
    // Високосный февраль и первое воскресенье сентября 2026 — обе величины
    // не зависят от локали, но проверить это стоит: локаль меняет таблицы
    // названий, и легко вообразить, что вместе с ними уезжает и начало недели.
    expect(dayjs("2026-02-10").daysInMonth()).toBe(28)
    expect(dayjs("2028-02-10").daysInMonth()).toBe(29)
    expect(dayjs("2026-09-05").date()).toBe(5)
    expect(dayjs("2026-09-06").day()).toBe(0)
    expect(dayjs("2026-09-05").format("YYYY-MM")).toBe("2026-09")
  })
})
